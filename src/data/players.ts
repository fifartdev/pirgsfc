export function getPlayerBySlug(slug: string): Player | undefined {
  return players.find((p) => p.slug === slug);
}

export function getFeaturedPlayers(): Player[] {
  return players.filter((p) => p.featured);
}

export function getRelatedPlayers(slug: string, count = 3): Player[] {
  const player = getPlayerBySlug(slug);
  if (!player) return [];
  const samePosition = players.filter((p) => p.slug !== slug && p.position === player.position);
  const others = players.filter((p) => p.slug !== slug && p.position !== player.position);
  return [...samePosition, ...others].slice(0, count);
}
