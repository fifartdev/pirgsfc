export function getPlayerBySlug(slug: string): Player | undefined {
  return players.find((p) => p.slug === slug);
}

export function getPlayersByDepartment(department: Department): Player[] {
  return players.filter((p) => p.department === department);
}

export function getFeaturedPlayers(): Player[] {
  return players.filter((p) => p.featured);
}

export function getRelatedPlayers(slug: string, count = 3): Player[] {
  const player = getPlayerBySlug(slug);
  if (!player) return [];
  const sameDept = players.filter((p) => p.slug !== slug && p.department === player.department);
  const samePosition = sameDept.filter((p) => p.position === player.position);
  const others = sameDept.filter((p) => p.position !== player.position);
  return [...samePosition, ...others].slice(0, count);
}
