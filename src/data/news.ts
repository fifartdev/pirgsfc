export function getArticleBySlug(slug: string): NewsArticle | undefined {
  return newsArticles.find((a) => a.slug === slug);
}

export function getLatestArticles(count = 3): NewsArticle[] {
  return [...newsArticles].sort((a, b) => b.date.localeCompare(a.date)).slice(0, count);
}

export function getFeaturedArticle(): NewsArticle {
  return newsArticles.find((a) => a.featured) ?? newsArticles[0];
}

export function getRelatedArticles(slug: string, count = 3): NewsArticle[] {
  const article = getArticleBySlug(slug);
  if (!article) return [];
  const sameCategory = newsArticles.filter((a) => a.slug !== slug && a.category === article.category);
  const others = newsArticles.filter((a) => a.slug !== slug && a.category !== article.category);
  return [...sameCategory, ...others].slice(0, count);
}
